/**
 * Resolves a comprehensive page summary for any pathname,
 * with intelligent dynamic matching for solutions and courses.
 */
export function getPageSummary(pathname = "/") {
  // Normalize pathname: remove hash, query, and trailing slash
  const cleanPath = (pathname.split("#")[0].split("?")[0] || "/").replace(/\/+$/, "") || "/";

  // 1. Direct match
  if (STATIC_PAGE_SUMMARIES[cleanPath]) {
    return STATIC_PAGE_SUMMARIES[cleanPath];
  }

  // 2. Dynamic Solutions match: /solutions/:slug
  if (cleanPath.startsWith("/solutions/")) {
    const slug = cleanPath.replace("/solutions/", "");
    const solution = SOLUTIONS.find((s) => s.slug === slug);
    if (solution) {
      return {
        route: cleanPath,
        title: solution.title,
        eyebrow: "ENTERPRISE SOLUTION",
        subtitle: solution.tagline || solution.shortTitle,
        readingTime: "45 sec read",
        whatItIs: `A dedicated deep dive into GK Nexergy's ${solution.title} practice. ${solution.description}`,
        howItIsUseful: [
          {
            target: "For Your Enterprise",
            benefit: `Enables your organization to leverage ${solution.shortTitle.toLowerCase()} with high reliability, scalable architecture, and full source code ownership.`,
          },
          {
            target: "Engineering Approach",
            benefit: `Executed through our phased lifecycle: ${solution.flow ? solution.flow.join(" → ") : "Discover → Design → Develop → Deploy"}.`,
          },
        ],
        keyHighlights: solution.features || [
          "Enterprise grade architecture",
          "Dedicated agile pod assignment",
          "Automated CI/CD and deployment",
          "Ongoing maintenance and SLA support",
        ],
        action: {
          label: solution.cta || "Discuss This Solution",
          to: "/contact",
        },
      };
    }
  }

  // 3. Dynamic Academy Courses match: /academy/:slug
  if (cleanPath.startsWith("/academy/")) {
    const slug = cleanPath.replace("/academy/", "");
    const course = COURSES.find((c) => c.slug === slug);
    if (course) {
      return {
        route: cleanPath,
        title: `${course.title} — ${course.subtitle}`,
        eyebrow: `ACADEMY: ${course.category.toUpperCase()}`,
        subtitle: course.tagline,
        readingTime: "45 sec read",
        whatItIs: `A hands-on, intensive training program in ${course.title}. ${course.description}`,
        howItIsUseful: [
          {
            target: "Who This Is For",
            benefit: course.audience || "Students, graduates, and professionals seeking production-level technical capability.",
          },
          {
            target: "Career Outcomes",
            benefit: course.outcomes ? course.outcomes.slice(0, 2).join(". ") : "Industry-recognized certificate, production portfolio projects, and interview preparation.",
          },
        ],
        keyHighlights: course.topics ? course.topics.slice(0, 5) : [
          "Hands-on lab exercises and attack/defense scenarios",
          "Production code repositories",
          "Direct architectural mentorship",
          "Tamper-proof verifiable certification",
        ],
        action: {
          label: "Inquire About This Course",
          to: "/contact",
        },
      };
    }
  }

  // 4. Default Fallback
  return {
    route: cleanPath,
    title: "GK Nexergy Experience",
    eyebrow: "PAGE OVERVIEW",
    subtitle: "Train • Build • Transform",
    readingTime: "30 sec read",
    whatItIs:
      "You are exploring GK Nexergy — an enterprise engineering and talent acceleration powerhouse based in Visakhapatnam, Andhra Pradesh.",
    howItIsUseful: [
      {
        target: "For Visitors",
        benefit:
          "Browse custom software services, industry solutions, and hands-on academy courses designed for real-world impact.",
      },
    ],
    keyHighlights: [
      "100% Client Code & IP Ownership",
      "Hands-on Academy with production-grade labs",
      "Dedicated Agile delivery pods",
      "Fast 10-minute response time",
    ],
    action: {
      label: "Explore Home",
      to: "/home",
    },
  };
}
